/**
 * Range ships its own world. Prices are modelled, not scraped: every city carries
 * a cost index, a mid-tier hotel and food anchor in USD, and a route factor that
 * says how competitive its air market is. [com.vythera.range.domain.BudgetEngine]
 * turns those into a real trip total for any party size, tier and travel mode.
 */
object DestinationCatalog {

    private fun vibes(spec: String): Set<Vibe> = spec.split(',')
        .mapNotNull { token ->
            val name = token.trim().uppercase()
            Vibe.entries.firstOrNull { it.name == name }
        }
        .toSet()

    private fun months(spec: String): Set<Int> =
        spec.split(',').mapNotNull { it.trim().toIntOrNull() }.toSet()

    @Suppress("LongParameterList")
    private fun d(
        id: String,
        city: String,
        country: String,
        cc: String,
        iata: String,
        lat: Double,
        lon: Double,
        region: Region,
        land: Landmass,
        cost: Double,
        fare: Double,
        hotel: Int,
        food: Int,
        vibeSpec: String,
        best: String,
        visa: VisaKind,
        visaCost: Int,
        pop: Double,
        exp: Double,
        blurb: String,
        highlights: String,
    ): Destination {
        val v = vibes(vibeSpec)
        return Destination(
            id = id,
            city = city,
            country = country,
            countryCode = cc,
            iata = iata,
            lat = lat,
            lon = lon,
            region = region,
            landmass = land,
            costIndex = cost,
            fareFactor = fare,
            hotelMid = hotel,
            foodMid = food,
            vibes = v,
            bestMonths = months(best),
            visaKind = visa,
            visaCostUsd = visaCost,
            popularity = pop,
            blurb = blurb,
            highlights = highlights.split('|').map { it.trim() },
            gradient = paletteFor(id, v),
            experienceScore = exp,
        )
    }

